import fs from 'node:fs';
import crypto from 'node:crypto';
const recipe='midnight_ghost_hunt/egg-midnight-ghost-hunt.json';
const base='internal/panel/game_library/scripts/';
const profiles=JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json'));
const profile=structuredClone(profiles[recipe]);
if(!profile) throw Error('Integrated MGH base missing');
const hashes={};
let script=profile.egg.scripts.installation.script;
script=script.replace(/cat > \.voltra\/([^ ]+) <<'VOLTRA_GHOST_LOVE_RENOWN_SOURCE'\n[\s\S]*?\nVOLTRA_GHOST_LOVE_RENOWN_SOURCE\n/g,(_,target)=>{
 const source=base+(target.endsWith('.json')?target:target.replaceAll('_','-'));
 const bytes=fs.readFileSync(source);
 hashes[source]=crypto.createHash('sha256').update(bytes).digest('hex');
 return `cat > .voltra/${target} <<'VOLTRA_GHOST_LOVE_RENOWN_SOURCE'\n${bytes.toString()}\nVOLTRA_GHOST_LOVE_RENOWN_SOURCE\n`;
});
const wrapper=fs.readFileSync(base+'mgh-runtime.py');
hashes[base+'mgh-runtime.py']=crypto.createHash('sha256').update(wrapper).digest('hex');
script=script.replace('python3 .voltra/ghost_love_renown.py install ghost',`cat > .voltra/mgh_runtime.py <<'VOLTRA_MGH_SOURCE'\n${wrapper.toString()}\nVOLTRA_MGH_SOURCE\npython3 .voltra/mgh_runtime.py install`);
if(!script.includes('VOLTRA_MGH_SOURCE')) throw Error('MGH installer dispatch changed');
profile.egg.scripts.installation.script=script;
profile.egg.startup=profile.egg.startup.replace('.voltra/ghost_love_renown.py run ghost','.voltra/mgh_runtime.py run');
if(!profile.egg.startup.includes('.voltra/mgh_runtime.py run')) throw Error('MGH startup dispatch changed');
profile.revision='mgh-preflight-authority-v2';
profile.verification='not_verified';
profile.detail='MGH-only pre-update validation and existing WindowsServer INI listener reconciliation. Source-only; root integration and served native acceptance blocked.';
profile.setup_steps.push('Startup controls own identity, map, mode, region, difficulty and password. Allocations own game/query/beacon ports. Existing WindowsServer Engine.ini listener scalars are reconciled at launch; gameplay/custom rules and unknown INI bytes stay operator-owned. Alternate config/identity flags are refused. Windows through Proton is compatibility execution, not publisher-supported Linux.');
fs.mkdirSync('.local/mgh',{recursive:true});
fs.writeFileSync('.local/mgh/profiles.json',JSON.stringify({[recipe]:profile},null,2)+'\n');
fs.writeFileSync('.local/mgh/embeds.json',JSON.stringify(hashes,null,2)+'\n');
console.log('Staged one MGH fragment with current helper embeds; canonical overrides unchanged.');
