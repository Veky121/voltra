import fs from 'node:fs';
const key='foundry/egg-foundry.json';
const output=process.argv[2]||'artifacts/game-parity-20261029/foundry-profile.json';
const catalog=JSON.parse(fs.readFileSync('internal/panel/game_library/upstream/catalog.json'));
const entry=catalog.entries.find(e=>e.path===key);
const original=entry.egg;
const profiles=JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json'));
const profile=structuredClone(profiles[key]);
profile.egg.variables=structuredClone(original.variables);
profile.egg.startup='exec /usr/bin/python3 .voltra/foundry-factory.py run';
profile.egg.config.files='{}';
let script=profile.egg.scripts.installation.script;
const helper=fs.readFileSync('internal/panel/game_library/scripts/foundry-factory.py','utf8').replace(/\r\n/g,'\n');
const block=`cat > .voltra/foundry-factory.py <<'VOLTRA_FOUNDRY_FACTORY'\n${helper}\nVOLTRA_FOUNDRY_FACTORY\npython3 .voltra/foundry-factory.py install`;
const embedded=/cat > \.voltra\/foundry-factory\.py <<'VOLTRA_FOUNDRY_FACTORY'\n[\s\S]*?\nVOLTRA_FOUNDRY_FACTORY\npython3 \.voltra\/foundry-factory\.py install/;
if(embedded.test(script)) script=script.replace(embedded,()=>block);
else if(script.includes('python3 .voltra/automation-sims.py install foundry')) script=script.replace('python3 .voltra/automation-sims.py install foundry',()=>block);
else throw Error('Missing installation hook');
if(!script.includes(helper)) throw Error('Staged helper differs from owned source');
profile.egg.scripts.installation.script=script;
profile.revision='foundry-preflight-20261030';
profile.verification='not_verified';
profile.detail='Source and offline fixtures only. All five gates await native acceptance.';
profile.setup_steps.push('Original ordered variable rows, defaults and permissions are retained exactly. Empty original SERVER_NAME requires operator input. Query port is administrator-owned. Native App.cfg is seeded once; later starts reconcile only allocated ports. Edit native game settings through shared settings UI, then restart. Unsafe or ambiguous native world/save paths fail closed.');
fs.mkdirSync('artifacts/game-parity-20261029',{recursive:true});
fs.writeFileSync(output,JSON.stringify({[key]:profile},null,2)+'\n');
