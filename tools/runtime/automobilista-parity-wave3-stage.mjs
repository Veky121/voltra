import fs from 'node:fs';
import assert from 'node:assert/strict';
const recipe='automobilista2/egg-automobilista2.json';
const overrides=JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json','utf8'));
const original=fs.readFileSync('internal/panel/game_library/scripts/assetto-ams-native.py','utf8').replaceAll('\r\n','\n');
const candidate=original;
const profile=structuredClone(overrides[recipe]);
const initial=structuredClone(profile);
const script=profile.egg.scripts.installation.script;
const marker="cat > .voltra/assetto-ams-native.py <<'VOLTRA_RACING_SOURCE'\n";
const start=script.indexOf(marker)+marker.length;
assert.ok(start>=marker.length,'Missing exact helper embed');
const end=script.indexOf('\nVOLTRA_RACING_SOURCE\n',start);
profile.egg.scripts.installation.script=script.slice(0,start)+candidate.trimEnd()+script.slice(end);
const edited=profile.egg.scripts.installation.script;
profile.egg.scripts.installation.script=initial.egg.scripts.installation.script;
assert.deepEqual(profile,initial,'Metadata, controls, permissions or unrelated script fields changed');
profile.egg.scripts.installation.script=edited;
fs.writeFileSync('artifacts/game-parity-20261029/automobilista-wave3-profile.json',JSON.stringify({[recipe]:profile},null,2)+'\n');
console.log(JSON.stringify({staged:true,variables:profile.egg.variables.length,metadata_preserved:true}));
