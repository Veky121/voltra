import fs from 'node:fs';
import crypto from 'node:crypto';
const key='fortresscraft_evolved/egg-fortresscraft-evolved.json';
const profile=structuredClone(JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json'))[key]);
const base='internal/panel/game_library/scripts/';
let script=profile.egg.scripts.installation.script;
const source=fs.readFileSync(base+'automation-sims.py','utf8').replace(/\r\n/g,'\n');
const marker="cat > .voltra/automation-sims.py <<'VOLTRA_AUTOMATION_SOURCE'\n";
const start=script.indexOf(marker), end=script.indexOf('\nVOLTRA_AUTOMATION_SOURCE\n',start+marker.length);
if(start<0||end<0)throw Error('Canonical family source boundary missing');
script=script.slice(0,start)+marker+source+'\nVOLTRA_AUTOMATION_SOURCE\n'+script.slice(end+'\nVOLTRA_AUTOMATION_SOURCE\n'.length);
const helper=fs.readFileSync(base+'automation-fortress-console.py','utf8').replace(/\r\n/g,'\n');
const insertion=`cat > .voltra/automation-fortress-console.py <<'VOLTRA_FORTRESS_CONSOLE_SOURCE'\n${helper}\nVOLTRA_FORTRESS_CONSOLE_SOURCE\n`;
script=script.replace('python3 .voltra/automation-sims.py install fortress',insertion+'python3 .voltra/automation-sims.py install fortress');
profile.egg.scripts.installation.script=script;
profile.setup_steps=profile.setup_steps.map(s=>s.replace('Original Ctrl-C is forwarded; native persistence remains untested.','Dashboard commands use authenticated loopback RCON; Stop submits publisher-supported quit once and preserves the native exit code. Native acceptance remains a separate check.'));
fs.mkdirSync('.local/fortress-native-source',{recursive:true});
fs.writeFileSync('.local/fortress-native-source/profiles.json',JSON.stringify({[key]:profile},null,2)+'\n');
console.log(JSON.stringify({path:key,helper_sha256:crypto.createHash('sha256').update(helper).digest('hex'),family_sha256:crypto.createHash('sha256').update(source).digest('hex')}));
