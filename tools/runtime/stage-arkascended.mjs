import fs from 'node:fs';
import crypto from 'node:crypto';
const recipe='ark_survival_ascended/egg-ark-survival-ascended.json';
const out='artifacts/game-parity-20261029/resume-wave4-arkascended';
const source='internal/panel/game_library/overrides.json';
const canonical=JSON.parse(fs.readFileSync(source));
const profile=structuredClone(canonical[recipe]);
const catalog=JSON.parse(fs.readFileSync('internal/panel/game_library/upstream/catalog.json'));
const original=catalog.entries.find(e=>e.path===recipe).egg.variables;
if(JSON.stringify(profile.egg.variables.slice(0,original.length))!==JSON.stringify(original)) throw Error('Original ordered controls differ');
let script=profile.egg.scripts.installation.script;
const hashes={};
let count=0;
script=script.replace(/(cat > \.voltra\/([^\s]+) <<'([^']+)'\n)([\s\S]*?)(\n\3(?=\n|$))/g,(all,head,installed,delimiter,body,tail)=>{
 const name=installed.replaceAll('_','-');
 const path='internal/panel/game_library/scripts/'+(fs.existsSync('internal/panel/game_library/scripts/'+installed)?installed:name);
 if(!fs.existsSync(path)) throw Error('Unknown helper '+installed);
 const text=fs.readFileSync(path,'utf8').replaceAll('\r\n','\n').trimEnd();
 if(text.split('\n').includes(delimiter)) throw Error('Heredoc collision');
 hashes[path]=crypto.createHash('sha256').update(fs.readFileSync(path)).digest('hex'); count++;
 return head+text+tail;
});
if(!count || !script.includes('def run(root, plan, env):')) throw Error('Missing ASA embed');
profile.egg.scripts.installation.script=script;
profile.verification='not_verified';
profile.revision='arkascended-resume-wave4-source';
profile.detail='Unserved source fixtures only; native acceptance blocked pending approved prerequisites and integration.';
fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(out+'/profile.json',JSON.stringify({[recipe]:profile},null,2)+'\n');
fs.writeFileSync(out+'/helper-hashes.json',JSON.stringify({recipe,source,source_sha256:crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex'),helpers:hashes},null,2)+'\n');
console.log('Staged ASA only, '+count+' current helpers; canonical unchanged.');
