import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const recipe='avorion/egg-avorion.json';
const source='internal/panel/game_library/scripts/avorion-runtime.py';
const candidate=source;
const overrides=JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json','utf8'));
const profile=structuredClone(overrides[recipe]);
const originalVariables=JSON.stringify(profile.egg.variables);
const original=fs.readFileSync(source,'utf8').replaceAll('\r\n','\n');
const replacement=fs.readFileSync(candidate,'utf8').replaceAll('\r\n','\n');
const old=profile.egg.scripts.installation.script;
const marker="cat > .voltra/avorion_runtime.py <<'VOLTRA_SOURCE'\n";
const begin=old.indexOf(marker);
assert.ok(begin>=0,'Exact adapter heredoc missing');
const contentStart=begin+marker.length;
const end=old.indexOf('\nVOLTRA_SOURCE\n',contentStart);
assert.ok(end>=0,'Exact adapter heredoc delimiter missing');
assert.equal(old.slice(contentStart,end).trimEnd(),original.trimEnd(),'Canonical helper and embedded helper disagree; root must reconcile source first');
profile.egg.scripts.installation.script=old.slice(0,contentStart)+replacement.trimEnd()+old.slice(end);
assert.equal(JSON.stringify(profile.egg.variables),originalVariables);
const reportPath='artifacts/game-parity-20261029/avorion-wave2-profile.json';
fs.writeFileSync(reportPath,JSON.stringify({[recipe]:profile},null,2)+'\n');
console.log(JSON.stringify({staged:reportPath,variables:profile.egg.variables.length,candidate_sha256:createHash('sha256').update(replacement).digest('hex'),canonical_overrides_unchanged:true}));
