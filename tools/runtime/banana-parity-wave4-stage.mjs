import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const key = 'banana_shooter/egg-banana-shooter.json';
const current = JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json'))[key];
const profile = structuredClone(current);
const canonical = 'internal/panel/game_library/scripts/banana-native-authority.py';
const source = canonical;
const body = fs.readFileSync(source, 'utf8').replaceAll('\r\n', '\n');
assert(body.endsWith('\n'), 'Canonical Python source must end in one newline');
assert(!body.includes('VOLTRA_BANANA_AUTHORITY_WAVE4'));
const old = '.voltra/light_games_next_runtime.py banana';
const authority = '.voltra/banana_native_authority.py';
assert(profile.egg.startup.endsWith(old) || profile.egg.startup.endsWith(authority));
profile.egg.startup = profile.egg.startup.replace(old, '.voltra/banana_native_authority.py');
const existing = /\ncat > \.voltra\/banana_native_authority\.py <<'VOLTRA_BANANA_AUTHORITY_WAVE4'\n([\s\S]*?)VOLTRA_BANANA_AUTHORITY_WAVE4\n/g;
const matches = [...profile.egg.scripts.installation.script.matchAll(existing)];
assert(matches.length <= 1, 'Repeated authority helper must be reviewed');
if(matches.length) assert.equal(matches[0][1], body, 'Existing deployed helper must match canonical bytes before reordering');
const installer = profile.egg.scripts.installation.script.replace(existing, '');
const terminal = 'python3 .voltra/light_games_next_install.py banana\n';
assert(installer.endsWith(terminal) && installer.split(terminal).length === 2, 'Keep the private preparation descriptor terminal guard exact');
const heredoc = `cat > .voltra/banana_native_authority.py <<'VOLTRA_BANANA_AUTHORITY_WAVE4'\n${body.replace(/\n$/, '')}\nVOLTRA_BANANA_AUTHORITY_WAVE4\n`;
profile.egg.scripts.installation.script = installer.slice(0, -terminal.length) + heredoc + terminal;
const embedded = profile.egg.scripts.installation.script.split("cat > .voltra/banana_native_authority.py <<'VOLTRA_BANANA_AUTHORITY_WAVE4'\n")[1].split('VOLTRA_BANANA_AUTHORITY_WAVE4\n')[0];
assert.equal(embedded, body, 'Deployed Banana helper must match canonical source bytes');
if(!profile.revision.endsWith('-native-authority-wave4')) profile.revision += '-native-authority-wave4';
const detail = ' Banana-only native name/token authority is covered by offline fixtures; entitlement, publisher schema and current native acceptance remain unverified.';
if(!profile.detail.includes(detail.trim())) profile.detail += detail;
const step = 'Existing native Browser.Server_Name and unambiguous Server.Login_Token/STEAM_GSLT values take precedence after creation. Startup controls seed missing values. Conflicting token aliases fail before startup updates. Dynamic Game settings document discovery still needs root integration.';
if(!profile.setup_steps.includes(step)) profile.setup_steps.push(step);
assert.deepEqual(profile.egg.variables, current.egg.variables);
for (const field of ['upstream_sha256', 'verification', 'platforms', 'defaults', 'required_ports', 'port_rules', 'settings_documents']) assert.deepEqual(profile[field], current[field]);
for (const field of ['config', 'docker_images', 'features']) assert.deepEqual(profile.egg[field], current.egg[field]);
const target = 'artifacts/game-parity-20261029/banana-wave4-profile.json';
fs.writeFileSync(target, JSON.stringify({[key]:profile}, null, 2) + '\n');
console.log(JSON.stringify({target, controls:profile.egg.variables.length, helper_sha256:crypto.createHash('sha256').update(body).digest('hex'), terminal_downloader:true, canonical_changed:false}));
