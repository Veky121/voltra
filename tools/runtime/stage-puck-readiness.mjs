import fs from 'node:fs';
import crypto from 'node:crypto';
const recipe = 'puck/egg-puck.json';
const profiles = JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json'));
const profile = structuredClone(profiles[recipe]);
if (!profile) throw Error('Missing exact Puck profile');
const parser = fs.readFileSync('internal/panel/game_library/scripts/puck-readiness.py', 'utf8');
let script = profile.egg.scripts.installation.script;
const marker = 'python3 .voltra/light_games_next_install.py puck';
if (script.split(marker).length !== 2) throw Error('Unexpected Puck installer layout');
const old = 'observer=PuckObserver(environment) if game==\'puck\' else None';
if (script.split(old).length !== 2) throw Error('Unexpected Puck observer layout');
script = script.replace(old, "from puck_readiness import PuckObserver as StrictPuckObserver\n observer=StrictPuckObserver(environment) if game=='puck' else None");
script = script.replace(marker, `cat > .voltra/puck_readiness.py <<'VOLTRA_PUCK_READINESS'\n${parser}\nVOLTRA_PUCK_READINESS\n${marker}`);
profile.egg.scripts.installation.script = script;
profile.revision = 'puck-strict-readiness-source-v2';
profile.verification = 'not_verified';
profile.detail += ' Strict proof parser candidate is source-only and unserved. Historical native acceptance does not verify this revision.';
const directory = 'artifacts/game-parity-20261029/puck-resume-source';
fs.mkdirSync(directory, {recursive:true});
fs.writeFileSync(`${directory}/profiles.fragment.json`, JSON.stringify({[recipe]:profile}, null, 2)+'\n');
console.log(JSON.stringify({recipe, output:`${directory}/profiles.fragment.json`, parser_sha256:crypto.createHash('sha256').update(parser).digest('hex')}));
