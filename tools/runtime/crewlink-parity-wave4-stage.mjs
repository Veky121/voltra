import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';

const recipe = 'among_us/bettercrewlink_server/egg-better-crewlink-server.json';
const canonical = 'internal/panel/game_library/overrides.json';
const before = fs.readFileSync(canonical);
const current = JSON.parse(before)[recipe];
const profile = structuredClone(current);
const helper = 'internal/panel/game_library/scripts/crewlink-controls.py';
const rawSource = fs.readFileSync(helper, 'utf8');
const source = rawSource.replaceAll('\r\n', '\n');
const payload = source.endsWith('\n') ? source : source + '\n';
const old = '.voltra/among-us-runtime.py crewlink';
assert(profile.egg.startup.endsWith(old) || profile.egg.startup.endsWith('.voltra/crewlink-controls.py'));
assert(!source.includes('\nVOLTRA_CREWLINK_WAVE4\n'));
profile.egg.startup = profile.egg.startup.replace(old, '.voltra/crewlink-controls.py');
profile.egg.scripts.installation.script = profile.egg.scripts.installation.script.replace(/\ncat > \.voltra\/crewlink-controls\.py <<'VOLTRA_CREWLINK_WAVE4'\n[\s\S]*?\nVOLTRA_CREWLINK_WAVE4\n/g, '');
const header = "cat > .voltra/crewlink-controls.py <<'VOLTRA_CREWLINK_WAVE4'\n";
profile.egg.scripts.installation.script += `\n${header}${payload}VOLTRA_CREWLINK_WAVE4\n`;
profile.settings_documents = {...profile.settings_documents, '/crewlink/config/peerConfig.yml': 'yaml'};
if (!profile.revision.endsWith('-allocated-listener-wave4')) profile.revision += '-allocated-listener-wave4';
const detail = ' Scoped source-only listener allocation validation and native peer configuration discovery; no new runtime acceptance.';
if (!profile.detail.endsWith(detail)) profile.detail += detail;
const setup = "The configured web listener must be among this server's allocations. Native peerConfig.yml remains authoritative. Integrated TURN needs an allocated listener, complete relay range and matching advertised/forwarded addresses.";
if (!profile.setup_steps.includes(setup)) profile.setup_steps.push(setup);
assert.deepEqual(profile.egg.variables, current.egg.variables);
for (const name of ['upstream_sha256', 'verification', 'defaults', 'platforms', 'port_rules', 'required_ports']) assert.deepEqual(profile[name], current[name]);
assert(fs.readFileSync(canonical).equals(before));
const output = 'artifacts/game-parity-20261029/crewlink-wave4-profile.json';
fs.writeFileSync(output, JSON.stringify({[recipe]: profile}, null, 2) + '\n');
const offset=profile.egg.scripts.installation.script.lastIndexOf(header)+header.length;
const end=profile.egg.scripts.installation.script.indexOf('VOLTRA_CREWLINK_WAVE4\n',offset);
assert.equal(profile.egg.scripts.installation.script.slice(offset,end),payload,'Exact normalized canonical embed mismatch');
const receipt={recipe,canonical_helper:helper,canonical_raw_sha256:createHash('sha256').update(rawSource).digest('hex'),embedded_sha256:createHash('sha256').update(payload).digest('hex'),baseline_overrides_sha256:createHash('sha256').update(before).digest('hex'),baseline_profile_sha256_compact_json:createHash('sha256').update(JSON.stringify(current)).digest('hex'),controls_preserved:profile.egg.variables.length,exact_embed_verified:true,canonical_overrides_changed:false};
fs.writeFileSync('artifacts/game-parity-20261029/crewlink-wave4-integration.json',JSON.stringify(receipt,null,2)+'\n');
console.log(JSON.stringify({output, ...receipt}));
