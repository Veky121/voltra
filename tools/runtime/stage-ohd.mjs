import fs from 'node:fs';
import crypto from 'node:crypto';
const recipe='operation_harsh_doorstop/egg-operation-harsh-doorstop.json';
const base='internal/panel/game_library/scripts/';
const profile=structuredClone(JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json'))[recipe]);
profile.egg.startup='exec env PYTHONHOME=/home/container/.voltra/python LD_LIBRARY_PATH=/home/container/.voltra/python/lib .voltra/python/bin/python3 .voltra/ohd_runtime.py run';
const source=fs.readFileSync(base+'ohd-runtime.py','utf8').replace(/^\uFEFF/,'');
let script=profile.egg.scripts.installation.script;
script=script.replace(/cat > \.voltra\/ohd_runtime.py <<'VOLTRA_OHD_SOURCE'\n[\s\S]*?\nVOLTRA_OHD_SOURCE\n/g,'').replace('python3 .voltra/ohd_runtime.py install','python3 .voltra/vr_tower_ohd.py install ohd');
const invocation='python3 .voltra/vr_tower_ohd.py install ohd';
if(!script.includes(invocation)) throw Error('OHD installer invocation changed; review required');
script=script.replace(invocation,`cat > .voltra/ohd_runtime.py <<'VOLTRA_OHD_SOURCE'\n${source}\nVOLTRA_OHD_SOURCE\npython3 .voltra/ohd_runtime.py install`);
profile.egg.scripts.installation.script=script;
profile.revision='ohd-native-file-wave30';
profile.detail='UNSERVED source fragment. Historical runtime_partial retained separately; changed wrapper requires affected native follow-up.';
const out='artifacts/game-parity-20261029/wave30-ohd';
fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(out+'/recipe-fragment.json',JSON.stringify({[recipe]:profile},null,2)+'\n');
const hashes={};
for(const match of script.matchAll(/cat > \.voltra\/([^ ]+) <<'([^']+)'\n([\s\S]*?)\n\2/g)) hashes['.voltra/'+match[1]]=crypto.createHash('sha256').update(match[3].replaceAll('\r\n','\n').replace(/\n*$/,'')+'\n').digest('hex');
fs.writeFileSync(out+'/runtime-sources.json',JSON.stringify(hashes,null,2)+'\n');
