import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
const key = 'craftopia/egg-craftopia.json';
const original = JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json'))[key];
const profile = structuredClone(original);
const canonical = 'internal/panel/game_library/scripts/craftopia-preflight.py';
const source = canonical;
const body = fs.readFileSync(source, 'utf8').replaceAll('\r\n', '\n');
assert(body.endsWith('\n'), 'Canonical Python source must end in one newline');
const old = '.voltra/crafting_runtime.py';
assert(profile.egg.startup.endsWith(old));
assert(!body.includes('VOLTRA_CRAFTOPIA_PREFLIGHT_WAVE5'));
profile.egg.startup = profile.egg.startup.replace(old, '.voltra/craftopia_preflight.py');
profile.egg.scripts.installation.script += `\ncat > .voltra/craftopia_preflight.py <<'VOLTRA_CRAFTOPIA_PREFLIGHT_WAVE5'\n${body.replace(/\n$/, '')}\nVOLTRA_CRAFTOPIA_PREFLIGHT_WAVE5\n`;
const embedded = profile.egg.scripts.installation.script.split("cat > .voltra/craftopia_preflight.py <<'VOLTRA_CRAFTOPIA_PREFLIGHT_WAVE5'\n")[1].split('VOLTRA_CRAFTOPIA_PREFLIGHT_WAVE5\n')[0];
assert.equal(embedded, body, 'Deployed Craftopia helper must match canonical source bytes');
profile.settings_documents = {...profile.settings_documents, '/ServerSetting.ini': 'ini'};
profile.revision += '-preflight-wave5';
profile.detail += ' Source-only Craftopia preflight now validates original runtime controls and managed native identities before automatic acquisition. Current campaign native acceptance remains pending.';
assert.deepEqual(profile.egg.variables, original.egg.variables);
for (const field of ['upstream_sha256', 'verification', 'platforms', 'defaults', 'required_ports', 'port_rules']) assert.deepEqual(profile[field], original[field]);
for (const field of ['config', 'docker_images', 'features']) assert.deepEqual(profile.egg[field], original.egg[field]);
const target = 'artifacts/game-parity-20261029/craftopia-wave5-profile.json';
fs.writeFileSync(target, JSON.stringify({[key]:profile}, null, 2) + '\n');
console.log(JSON.stringify({target,controls:profile.egg.variables.length,source_sha256:crypto.createHash('sha256').update(body).digest('hex'),canonical_changed:false}));
