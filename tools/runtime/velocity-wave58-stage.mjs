import fs from 'node:fs';
import path from 'node:path';
const out=process.argv[2];
if(!out)throw Error('Explicit isolated output directory required');
if(fs.existsSync(out))throw Error('Output already exists; preserve previous evidence');
const recipe='minecraft/proxy/java/velocity/egg-velocity.json';
const profile=structuredClone(JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json'))[recipe]);
const script=profile.egg.scripts.installation.script;
const marker="cat > .voltra/proxy_family_install.py <<'VOLTRA_PROXY_SOURCE'\n";
const start=script.indexOf(marker)+marker.length,end=script.indexOf('\nVOLTRA_PROXY_SOURCE',start);
if(start<marker.length||end<start)throw Error('Missing exact helper block');
profile.egg.scripts.installation.script=script.slice(0,start)+fs.readFileSync('internal/panel/game_library/scripts/proxy-family-install.py','utf8').trimEnd()+script.slice(end);
profile.revision='velocity-wave58-preflight-v1';
profile.verification='not_verified';
profile.detail='Unapplied source-only Velocity preflight; historical native proof is not current acceptance.';
fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,'profiles.json'),JSON.stringify({[recipe]:profile},null,2)+'\n');
for(const match of profile.egg.scripts.installation.script.matchAll(/cat > \.voltra\/([^ ]+) <<'VOLTRA_PROXY_SOURCE'\n([\s\S]*?)\nVOLTRA_PROXY_SOURCE/g))fs.writeFileSync(path.join(out,match[1]),match[2]+'\n');
console.log(out);
