import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const path='solace_crafting/egg-solace-crafting.json';
const canonical=JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json'));
const profile=structuredClone(canonical[path]);
assert(profile,'Canonical Solace recipe missing');
const source=fs.readFileSync('internal/panel/game_library/scripts/fantasy-worlds-runtime.py','utf8');
const marker="cat > .voltra/fantasy_worlds_runtime.py <<'VOLTRA_FANTASY_SOURCE'\n";
const script=profile.egg.scripts.installation.script;
const start=script.indexOf(marker),end=script.indexOf('\nVOLTRA_FANTASY_SOURCE\n',start+marker.length);
assert(start>=0&&end>start&&script.indexOf(marker,start+1)<0,'Expected exactly one runtime snapshot');
profile.egg.scripts.installation.script=script.slice(0,start+marker.length)+source+script.slice(end);
profile.setup_steps=profile.setup_steps.map(step=>step.includes('Console input and Ctrl+C use the shared native PTY.')?'Console input uses the shared native PTY. Solace Ctrl+C explicitly sends native SIGINT to the owned process group; raw exit is retained. Native save-on-shutdown, stop and listing behavior remain unverified.':step);
assert.equal(profile.verification,canonical[path].verification);
assert.deepEqual(profile.egg.variables,canonical[path].egg.variables);
const out='.local/solace-signal';fs.mkdirSync(out,{recursive:true});
const bytes=JSON.stringify({[path]:profile},null,2)+'\n';fs.writeFileSync(out+'/profiles.json',bytes);
fs.writeFileSync(out+'/source-hashes.json',JSON.stringify({'fantasy-worlds-runtime.py':sha(source),'profiles.json':sha(bytes)},null,2)+'\n');
console.log(JSON.stringify({path,verification:profile.verification,helper_sha256:sha(source),stage_sha256:sha(bytes)}));
