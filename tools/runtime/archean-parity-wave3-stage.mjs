import fs from 'node:fs';
import assert from 'node:assert/strict';
const recipe='Archean/egg-archean.json';
const before=JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json'))[recipe];
const profile=structuredClone(before);
const helper=fs.readFileSync('internal/panel/game_library/scripts/archean-file-authority.py','utf8');
const old='.voltra/vehicle-sims.py run archean';
assert(profile.egg.startup.includes(old));
profile.egg.startup=profile.egg.startup.replace(old,'.voltra/archean_parity_wave3.py run archean');
const marker='python3 .voltra/bundle-debian-python.py';
assert.equal(profile.egg.scripts.installation.script.split(marker).length,2);
assert(!helper.includes('\nVOLTRA_ARCHEAN_AUTHORITY\n'));
profile.egg.scripts.installation.script=profile.egg.scripts.installation.script.replace(marker,`cat > .voltra/archean_parity_wave3.py <<'VOLTRA_ARCHEAN_AUTHORITY'\n${helper}\nVOLTRA_ARCHEAN_AUTHORITY\n${marker}`);
profile.settings_documents={'/Archean-data/server/server.ini':'ini'};
assert.deepEqual(profile.egg.variables,before.egg.variables);
const restored=structuredClone(profile);
delete restored.settings_documents;
restored.egg.startup=before.egg.startup;
restored.egg.scripts.installation.script=before.egg.scripts.installation.script;
assert.deepEqual(restored,before);
fs.writeFileSync('artifacts/game-parity-20261029/archean-wave3-profile.json',JSON.stringify({[recipe]:profile},null,2)+'\n');
console.log('Archean fragment staged; original ordered controls and metadata preserved.');
