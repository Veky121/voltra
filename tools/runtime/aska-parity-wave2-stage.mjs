import fs from 'node:fs';
import crypto from 'node:crypto';
const recipe = 'Aska/egg-aska.json';
const canonical = JSON.parse(fs.readFileSync('internal/panel/game_library/overrides.json'));
const profile = structuredClone(canonical[recipe]);
const wrapper = fs.readFileSync('internal/panel/game_library/scripts/aska-file-authority.py', 'utf8');
if (!['.voltra/unreal_survival_next.py run aska', '.voltra/aska_file_authority.py run aska'].some(x => profile.egg.startup.includes(x))) throw Error('Unexpected ASKA startup');
profile.egg.startup = profile.egg.startup.replace('.voltra/unreal_survival_next.py run aska', '.voltra/aska_file_authority.py run aska');
profile.settings_documents = {...profile.settings_documents, '/server properties.txt': 'ini'};
const installer = profile.egg.scripts.installation.script;
const block = /\ncat > .voltra\/aska_file_authority\.py <<'VOLTRA_ASKA_AUTHORITY'\r?\n[\s\S]*?\r?\nVOLTRA_ASKA_AUTHORITY\r?\n/g;
const matches = [...installer.matchAll(block)];
if (matches.length > 1 || (installer.includes('VOLTRA_ASKA_AUTHORITY') && matches.length !== 1)) throw Error('Ambiguous ASKA wrapper embed');
profile.egg.scripts.installation.script = installer.replace(block, '') + `\ncat > .voltra/aska_file_authority.py <<'VOLTRA_ASKA_AUTHORITY'\n${wrapper}\nVOLTRA_ASKA_AUTHORITY\n`;
profile.setup_steps.push('Native settings retain authority. Token presence, literal values and keep-world-alive boolean are checked before startup auto-update. An operator-owned GSLT is required; native readiness and save/stop remain unverified.');
profile.revision += '-preflight-20261030';
profile.verification = 'not_verified';
profile.detail = 'Offline ASKA file-authority preparation only. Native installation, typed settings UI, lifecycle and player acceptance remain pending.';
const output = process.argv[2] || 'artifacts/game-parity-20261029/aska-resume-profile.json';
fs.writeFileSync(output, JSON.stringify({[recipe]: profile}, null, 2) + '\n');
if (JSON.stringify(profile.egg.variables) !== JSON.stringify(canonical[recipe].egg.variables)) throw Error('Variable rows changed');
console.log(JSON.stringify({output, originalVariables: profile.egg.variables.length, wrapperSha256: crypto.createHash('sha256').update(wrapper).digest('hex')}));
